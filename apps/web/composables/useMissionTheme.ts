function palette(label: string, colors: Record<string, string>): MissionPalette {
  return { label, colors };
}

export function applyMissionTheme(theme: MissionTheme): void {
  if (!import.meta.client) return;
  const palette = missionThemes[theme] ?? missionThemes.mint;
  const root = document.documentElement;
  for (const [name, value] of Object.entries(palette.colors))
    root.style.setProperty(`--${name}`, value);
  root.dataset.missionTheme = theme;
}
